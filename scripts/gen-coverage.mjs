#!/usr/bin/env node
// Coverage audit: every docs page (tests/api-docs-snapshot.txt) × tool registry
// (from src/tools/*.ts) with curated mapping (tests/api-coverage-map.json).
// Generates docs/COVERAGE.md. Fails on drift (new docs page not in map, or
// a "covered"/"partial" entry loses its tools).

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const mapPath = path.join(root, 'tests', 'api-coverage-map.json');
const snapshotPath = path.join(root, 'tests', 'api-docs-snapshot.txt');
const outPath = path.join(root, 'docs', 'COVERAGE.md');

const slug = (url) =>
  url.replace('https://yandex.ru/support/tracker/ru/api/', '').replace(/\.md$/, '');

const snapshot = readFileSync(snapshotPath, 'utf8').trim().split('\n').map(slug).sort();
const map = JSON.parse(readFileSync(mapPath, 'utf8'));

// extract registered tools from source
const toolsDir = path.join(root, 'src', 'tools');
const { readdirSync } = await import('node:fs');
const registered = new Set();
for (const f of readdirSync(toolsDir).filter((x) => x.endsWith('.ts'))) {
  const src = readFileSync(path.join(toolsDir, f), 'utf8');
  for (const m of src.matchAll(/'[a-z_0-9]+'/g)) registered.add(m[0].slice(1, -1));
}

// validate map
const errors = [];
for (const [slug, entry] of Object.entries(map)) {
  if (!snapshot.includes(slug) && !['get_link_types'].some((t) => entry.tools?.includes(t))) {
    errors.push(`map: page '${slug}' no longer in docs snapshot`);
  }
  if (entry.status === 'covered' || entry.status === 'partial') {
    for (const t of entry.tools ?? []) {
      if (!registered.has(t)) errors.push(`map: tool '${t}' on page '${slug}' is not registered`);
    }
  }
}

// validate that all pages are in map
const missing = snapshot.filter((s) => !map[s]);
for (const s of missing) {
  errors.push(`snapshot page '${s}' not in map — run with --update and curate`);
}

// stats
const counts = { covered: 0, partial: 0, reference: 0 };
for (const e of Object.values(map)) counts[e.status] = (counts[e.status] ?? 0) + 1;

// group by top-level (issues/queues/entities/...)
const groups = {};
for (const [slug, entry] of Object.entries(map)) {
  const top = slug.split('/')[0];
  (groups[top] ??= []).push([slug, entry]);
}

// generate markdown (docs7 frontmatter: title is required for site validation)
const lines = [
  '---',
  'title: "Карта покрытия API"',
  'description: "Все 199 страниц API Трекера v3 и каким из 187 инструментов каждая покрыта"',
  '---',
  '',
  '# Tool coverage map',
  '',
  'Auto-generated by `scripts/gen-coverage.mjs` — **do not edit by hand**.',
  'To update: `npm run coverage` (regenerate) then commit.',
  '',
  `**Status:** ${counts.covered} covered, ${counts.reference} reference-only, ${counts.partial} partial.`,
  '',
];

const emoji = { covered: '✅', partial: '⚠️', reference: '📄' };
const label = { covered: 'covered', partial: 'partial', reference: 'reference' };

for (const [group, entries] of Object.entries(groups).sort()) {
  const ok = entries.filter(([, e]) => e.status === 'covered').length;
  lines.push(`## ${group}/`);
  lines.push('');
  lines.push('| # | Docs page | Status | Tools |');
  lines.push('|---|---|---|---|');
  for (const [slug, e] of entries.sort()) {
    const name = slug.split('/').pop();
    const tools = (e.tools ?? []).map((t) => `\`${t}\``).join('<br>');
    lines.push(`| | [\`${name}\`](https://yandex.ru/support/tracker/ru/api/${slug}.md) | ${emoji[e.status]} ${label[e.status]} | ${tools} |`);
  }
  lines.push('');
}

if (errors.length) {
  console.error('❌ coverage drift:\n' + errors.map((e) => `  - ${e}`).join('\n'));
  process.exit(1);
}

if (process.argv.includes('--check')) {
  console.log(`✓ coverage in sync: ${counts.covered} covered, ${counts.reference} reference, ${counts.partial} partial`);
  process.exit(0);
}

writeFileSync(path.join(root, 'docs', 'COVERAGE.md'), lines.join('\n'));
console.log(`✓ docs/COVERAGE.md written: ${counts.covered} covered, ${counts.reference} reference, ${counts.partial} partial across ${Object.keys(groups).length} groups`);
